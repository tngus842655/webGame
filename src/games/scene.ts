import { isDarkTheme } from '@/shared/theme'

// 게임 판의 '바탕'만 테마를 탄다 — 판 색, 여백, 그릇(보드·트레이·벽),
// 캔버스 위 글자와 조작 안내가 여기에 해당한다.
//
// 말은 넘기지 않는다. 과일·블록·보석·타일처럼 그 게임을 그 게임이게 하는 색은
// 두 테마에서 같은 값을 쓴다 — 어둡게 바꾸면 다른 게임이 된다.
//
// 캔버스는 CSS 변수를 못 읽으므로 값으로 받아 간다. 게임은 매 프레임 다시
// 그리니 설정에서 테마를 바꾸면 그 자리에서 반영된다 (i18n과 같은 방식).
//
// 원래부터 어두운 판을 쓰는 게임(우주·밤하늘·펠트 등)은 부르지 않는다.
// 두 테마에서 이미 같은 얼굴이라 바꿀 것이 없다.
export function ground(light: string, dark: string): string {
  return isDarkTheme() ? dark : light
}
