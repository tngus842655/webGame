const messages: Record<Locale, CoreDict> = {
  ko,
  en,
  ja,
  'zh-CN': zhCN,
  es,
  'pt-BR': ptBR,
  fr,
  de,
  ru,
  id,
  vi,
  th,
  tr,
}

function detectLocale(): Locale {
  const saved = localStorage.getItem(STORAGE_KEY)
  if (saved && messages[saved as Locale]) return saved as Locale
  for (const lang of navigator.languages ?? [navigator.language]) {
    const lower = lang.toLowerCase()
    if (lower.startsWith('zh')) return 'zh-CN'
    if (lower.startsWith('pt')) return 'pt-BR'
    const short = lower.split('-')[0] as Locale
    if (messages[short]) return short
  }
  return 'en'
}

export const locale = ref<Locale>(detectLocale())

export type TranslationKey = keyof typeof en

export function t(key: TranslationKey, params?: Record<string, string | number>): string {
  let text = messages[locale.value][key] ?? en[key] ?? key
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replace(`{${name}}`, String(value))
    }
  }
  return text
}

function applyToDocument() {
  document.documentElement.lang = locale.value
  document.title = t('app.title')
}

export function setLocale(next: Locale) {
  locale.value = next
  localStorage.setItem(STORAGE_KEY, next)
  applyToDocument()
}

